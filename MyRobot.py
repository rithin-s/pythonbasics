import turtle
user_input = input("Is the robot sad or happy or hungry?")

rithin = turtle.Turtle()
turtle.Screen().bgcolor("black")
turtle.title("rithin")
rithin.shape("turtle")
rithin.color("grey")
rithin.forward(200)
rithin.right(90)
rithin.forward(200)
rithin.right(90)
rithin.forward(200)
rithin.right(90)
rithin.forward(200)
rithin.right(90)
rithin.forward(100)
rithin.left(45)
rithin.forward(100)
rithin.backward(100)
rithin.left(90)
rithin.forward(100)
rithin.left(90)
rithin.penup()
rithin.left(90)
rithin.forward(100)
rithin.right(45)
rithin.forward(60)
rithin.right(135)
rithin.forward(25)
rithin.color("red")
rithin.begin_fill()
rithin.pendown()
rithin.circle(30)
rithin.end_fill()
rithin.color("grey")
rithin.penup()
rithin.right(135)
rithin.forward(100)
rithin.left(90)
rithin.backward(20)
rithin.pendown()
rithin.color("red")
rithin.begin_fill()
rithin.circle(30)
rithin.end_fill()
rithin.color("grey")
rithin.penup()
rithin.right(180)
rithin.forward(100)
rithin.right(90)
rithin.pendown()
if user_input == "The robot is sad" :
    rithin.penup()
    rithin.forward(25)
    rithin.right(90)
    rithin.pendown()
    rithin.circle(50,180)
elif user_input == "The robot is happy" :
    rithin.penup()
    rithin.forward(125)
    rithin.right(90)
    rithin.forward(50)
    rithin.left(180)
    rithin.pendown()
    rithin.circle(50,180)
elif user_input == "The robot is hungry" :
    rithin.penup()
    rithin.forward(75)
    rithin.right(90)
    rithin.forward(50)
    rithin.left(90)
    rithin.pendown()
    rithin.circle(40,360)
else:
    rithin.penup()
    rithin.forward(25)
    rithin.pendown()
    rithin.forward(125)
    rithin.penup()
    rithin.forward(25)
turtle.Screen().exitonclick()